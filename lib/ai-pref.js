// Whether the board shows its AI-written explanations (both boards).
//
// Everything the board explains is written by AI from a CRS report and labelled so. A reader who does not want
// it can turn it off: the choice is kept in this browser (localStorage; the page works without it) and applied
// to <html> as soon as this script runs, which is in the <head>, so the explanations never flash on before they
// go. CSS does the hiding: `html.ai-off .ai-block` is the inline explanations, and lib/info-popup.js writes a
// rule per AI entry for its (?) buttons. An entry that is not AI-written (the moment of silence's Deschler quote)
// stays.
//
//   AiPref.isOn()        AiPref.set(true | false)
//
// Two controls: a "Hide AI summaries" button added to every `.ai-block`, and any `[data-ai-toggle]` button (the
// footer's), whose label says the current state. Either one opens a window with a switch, and the switch is what changes the setting, in either direction.

(function (root) {
  'use strict';

  const KEY = 'ai-summaries';
  let off = false;
  try { off = localStorage.getItem(KEY) === 'off'; } catch (e) { /* private window: default on */ }

  const html = document.documentElement;
  html.classList.toggle('ai-off', off);

  function paint() {
    html.classList.toggle('ai-off', off);
    for (const b of document.querySelectorAll('[data-ai-toggle]')) {
      b.textContent = off ? 'Turn on AI summaries' : 'Turn off AI summaries';   // the action, not the state
    }
  }

  function set(on) {
    off = !on;
    try { localStorage.setItem(KEY, off ? 'off' : 'on'); } catch (e) { /* kept for this visit only */ }
    paint();
  }

  function addButtons() {
    for (const block of document.querySelectorAll('.ai-block')) {
      if (block.querySelector('.ai-off-btn')) continue;
      const b = document.createElement('button');
      b.type = 'button';
      b.className = 'ai-off-btn';
      b.textContent = 'Hide AI summaries';
      b.title = 'Turn off AI summaries (asks first; the footer turns them back on)';
      // On the same line as the source note ("Summary generated by AI from CRS Report ..."), at its right; the note wraps when it must. A block with no note ends with the button.
      const note = block.querySelector(':scope > .speech-mode-ai-note');
      if (note) {
        const row = document.createElement('div');
        row.className = 'ai-note-row';
        note.before(row);
        row.append(note, b);
      } else {
        block.appendChild(b);
      }
    }
  }

  // THE AI SUMMARIES WINDOW: pressing any AI button (the footer's, or a panel's "Hide AI summaries") opens a window that says what the setting does, and the SWITCH in it is what changes it, in either direction:
  // two steps, so the setting is never flipped by a stray press. It shows the state the page is in and offers the other; Escape, the X and a press outside close it with nothing changed. It uses the site's modal
  // chrome (.tm-picker) and focus trap. Flipping the switch applies at once; the window then says so and stays open until the reader closes it.
  let modal = null;
  const STAR = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M12 2.2l2.3 6.6 6.7 2.4-6.7 2.4L12 20.2l-2.3-6.6L3 11.2l6.7-2.4z"/><path class="ai-star-s" d="M19 3.2l.8 2.2 2.2.8-2.2.8-.8 2.2-.8-2.2-2.2-.8 2.2-.8z"/></svg>';
  const COPY = {
    on: { title: 'Turn off AI Summaries?', text: 'This setting will disable the AI-written summaries attached to some panels. The summaries are static and are drafted by artificial intelligence after reading select CRS articles.' },
    off: { title: 'Turn on AI Summaries?', text: 'This setting will enable the AI-written summaries attached to some panels. The summaries are static and are drafted by artificial intelligence after reading select CRS articles.' },
  };

  function closeModal() {
    if (!modal) return;
    const { ov, trap, onKey } = modal; modal = null;
    document.removeEventListener('keydown', onKey);
    ov.classList.remove('is-open');
    setTimeout(() => ov.remove(), 220);
    if (trap) trap.release();   // focus goes back to the button that opened it
  }

  function burst(track) {   // a few sparks off the knob when summaries come on
    if (matchMedia('(prefers-reduced-motion: reduce)').matches) return;
    for (let i = 0; i < 10; i++) {
      const sp = document.createElement('i');
      sp.className = 'ai-spark';
      sp.style.setProperty('--a', `${i * 36 + Math.random() * 20}deg`);
      sp.style.setProperty('--d', `${18 + Math.random() * 14}px`);
      track.appendChild(sp);
      setTimeout(() => sp.remove(), 800);
    }
  }

  function openModal() {
    if (modal) return;
    const startOn = !off;   // the state the page is in; the switch shows it and flipping it asks for the other
    const ov = document.createElement('div');
    ov.className = 'tm-picker-overlay ai-modal-overlay';
    ov.innerHTML = `<div class="tm-picker ai-modal ${startOn ? 'is-on' : 'is-off'}" role="dialog" aria-modal="true" aria-labelledby="ai-modal-title">
        <div class="tm-picker-head"><span class="ai-badge" aria-hidden="true">${STAR}</span><button type="button" class="tm-picker-close" aria-label="Close"></button></div>
        <h2 class="ai-modal-title" id="ai-modal-title">${COPY[startOn ? 'on' : 'off'].title}</h2>
        <p class="ai-modal-text">${COPY[startOn ? 'on' : 'off'].text}</p>
        <p class="ai-modal-note">AI-written text will be clearly labelled with a purple-tinted background to distinguish it. Look for this <span class="ai-robot" role="img" aria-label="robot"></span> icon for identification.</p>
        <div class="ai-modal-row">
          <span class="ai-modal-label" id="ai-switch-label">AI Summaries</span>
          <button type="button" class="ai-switch${startOn ? ' is-on' : ''}" role="switch" aria-checked="${startOn}" aria-labelledby="ai-switch-label"><span class="ai-switch-state">${startOn ? 'On' : 'Off'}</span><span class="ai-switch-track"><span class="ai-switch-knob">${STAR}</span></span></button>
        </div>
        <p class="ai-modal-done" role="status" aria-live="polite"></p>
      </div>`;
    document.body.appendChild(ov);
    const box = ov.querySelector('.ai-modal'), sw = ov.querySelector('.ai-switch'), done = ov.querySelector('.ai-modal-done');
    const onKey = (e) => { if (e.key === 'Escape') closeModal(); };
    document.addEventListener('keydown', onKey);
    const trap = root.FocusTrap ? root.FocusTrap.activate(box, { initial: '.ai-switch' }) : null;
    modal = { ov, trap, onKey };
    ov.querySelector('.tm-picker-close').addEventListener('click', closeModal);
    ov.addEventListener('click', (e) => { if (e.target === ov) closeModal(); });
    sw.addEventListener('click', () => {
      const on = sw.getAttribute('aria-checked') !== 'true';   // the switch's new state
      sw.setAttribute('aria-checked', String(on)); sw.classList.toggle('is-on', on);
      box.classList.toggle('is-on', on); box.classList.toggle('is-off', !on);
      sw.querySelector('.ai-switch-state').textContent = on ? 'On' : 'Off';
      set(on);
      if (on) burst(sw.querySelector('.ai-switch-track'));
      done.textContent = on ? 'AI Summaries are on.' : 'AI Summaries are off. This button turns them back on.';
    });
    requestAnimationFrame(() => ov.classList.add('is-open'));
  }

  document.addEventListener('click', (e) => {
    const t = e.target.closest && e.target.closest('[data-ai-toggle], .ai-off-btn');
    if (!t) return;
    openModal();   // every AI button asks, whichever way it would go; the switch in the window does it
  });

  document.addEventListener('DOMContentLoaded', () => { addButtons(); paint(); });

  root.AiPref = { isOn: () => !off, set };
})(typeof globalThis !== 'undefined' ? globalThis : this);
