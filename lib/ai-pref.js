// Whether the board shows its AI-written explanations (both boards).
//
// Everything the board explains is written by AI from a CRS report and labelled so. A reader who does not want
// it can turn it off: the choice is kept in this browser (localStorage; the page works without it) and applied
// to <html> as soon as this script runs, which is in the <head>, so the explanations never flash on before they
// go. CSS does the hiding: `html.ai-off .ai-block` is the inline explanations, and lib/info-popup.js writes a
// rule per AI entry for its (?) buttons. An entry that is not AI-written (the moment of silence's Deschler quote)
// stays.
//
//   AiPref.isOn()        AiPref.set(true | false)
//
// Two controls: a "Hide AI summaries" button added to every `.ai-block`, and any `[data-ai-toggle]` button (the
// footer's), whose label says the current state. Either one, when summaries are on, opens a window with a switch: turning off takes that second step.

(function (root) {
  'use strict';

  const KEY = 'ai-summaries';
  let off = false;
  try { off = localStorage.getItem(KEY) === 'off'; } catch (e) { /* private window: default on */ }

  const html = document.documentElement;
  html.classList.toggle('ai-off', off);

  function paint() {
    html.classList.toggle('ai-off', off);
    for (const b of document.querySelectorAll('[data-ai-toggle]')) {
      b.textContent = off ? 'Turn on AI summaries' : 'Turn off AI summaries';   // the action, not the state
    }
  }

  function set(on) {
    off = !on;
    try { localStorage.setItem(KEY, off ? 'off' : 'on'); } catch (e) { /* kept for this visit only */ }
    paint();
  }

  function addButtons() {
    for (const block of document.querySelectorAll('.ai-block')) {
      if (block.querySelector('.ai-off-btn')) continue;
      const b = document.createElement('button');
      b.type = 'button';
      b.className = 'ai-off-btn';
      b.textContent = 'Hide AI summaries';
      b.title = 'Turn off AI summaries (asks first; the footer turns them back on)';
      // On the same line as the source note ("Summary generated by AI from CRS Report ..."), at its right; the note wraps when it must. A block with no note ends with the button.
      const note = block.querySelector(':scope > .speech-mode-ai-note');
      if (note) {
        const row = document.createElement('div');
        row.className = 'ai-note-row';
        note.before(row);
        row.append(note, b);
      } else {
        block.appendChild(b);
      }
    }
  }

  // TURNING OFF IS TWO STEPS: pressing a "turn off" button opens a window that says what the setting does, and the switch in it is what turns it off. Turning ON needs no asking, so the footer's
  // "Turn on AI summaries" does it at once. The window uses the site's modal chrome (.tm-picker) and focus trap; Escape, the X and a press outside close it with nothing changed.
  let modal = null, closeTimer = null;

  function closeModal() {
    if (!modal) return;
    clearTimeout(closeTimer);
    const { ov, trap, onKey } = modal; modal = null;
    document.removeEventListener('keydown', onKey);
    ov.classList.remove('is-open');
    setTimeout(() => ov.remove(), 220);
    if (trap) trap.release();   // focus goes back to the button that opened it
  }

  function openModal() {
    if (modal) return;
    const ov = document.createElement('div');
    ov.className = 'tm-picker-overlay ai-modal-overlay';
    ov.innerHTML = `<div class="tm-picker ai-modal" role="dialog" aria-modal="true" aria-labelledby="ai-modal-title">
        <div class="tm-picker-head"><h2 class="ai-modal-title" id="ai-modal-title">Turn off AI Summaries?</h2><button type="button" class="tm-picker-close" aria-label="Close"></button></div>
        <p class="ai-modal-text">This setting will disable the AI-written summaries attached to some panels. The summaries are static and are drafted by artificial intelligence after reading select CRS articles.</p>
        <div class="ai-modal-row">
          <span class="ai-modal-label" id="ai-switch-label">AI Summaries</span>
          <button type="button" class="ai-switch is-on" role="switch" aria-checked="true" aria-labelledby="ai-switch-label"><span class="ai-switch-state">On</span><span class="ai-switch-track"><span class="ai-switch-knob"></span></span></button>
        </div>
        <p class="ai-modal-done" role="status" aria-live="polite"></p>
      </div>`;
    document.body.appendChild(ov);
    const sw = ov.querySelector('.ai-switch'), done = ov.querySelector('.ai-modal-done');
    const onKey = (e) => { if (e.key === 'Escape') closeModal(); };
    document.addEventListener('keydown', onKey);
    const trap = root.FocusTrap ? root.FocusTrap.activate(ov.querySelector('.tm-picker'), { initial: '.ai-switch' }) : null;
    modal = { ov, trap, onKey };
    ov.querySelector('.tm-picker-close').addEventListener('click', closeModal);
    ov.addEventListener('click', (e) => { if (e.target === ov) closeModal(); });
    sw.addEventListener('click', () => {
      const on = sw.getAttribute('aria-checked') !== 'true';   // the switch's new state
      sw.setAttribute('aria-checked', String(on)); sw.classList.toggle('is-on', on);
      sw.querySelector('.ai-switch-state').textContent = on ? 'On' : 'Off';
      set(on);
      clearTimeout(closeTimer);
      done.textContent = on ? '' : 'AI Summaries are off. The footer turns them back on.';
      if (!on) closeTimer = setTimeout(closeModal, 1400);   // long enough to read it
    });
    requestAnimationFrame(() => ov.classList.add('is-open'));
  }

  document.addEventListener('click', (e) => {
    const t = e.target.closest && e.target.closest('[data-ai-toggle], .ai-off-btn');
    if (!t) return;
    if (t.hasAttribute('data-ai-toggle') && off) set(true);   // the footer's "turn on": no asking
    else openModal();                                          // either "turn off" button: ask, and let the switch do it
  });

  document.addEventListener('DOMContentLoaded', () => { addButtons(); paint(); });

  root.AiPref = { isOn: () => !off, set };
})(typeof globalThis !== 'undefined' ? globalThis : this);
